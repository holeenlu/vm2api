export const ROUTES = Object.freeze(
  TABLE.map(([method, path, auth, kind, roles = [], audit = 'none']) =>
    Object.freeze({ method, path, auth, kind, roles: Object.freeze(roles), audit }),
  ),
)

const escapeRe = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const exact = new Map()
const patterns = []
for (const route of ROUTES) {
  const segments = route.path.split('/')
  const params = segments.filter((segment) => segment.startsWith(':')).length
  if (!params) exact.set(`${route.method} ${route.path}`, route)
  else
    patterns.push({
      route,
      params,
      re: new RegExp(`^${segments.map((s) => (s.startsWith(':') ? '[^/]+' : escapeRe(s))).join('/')}$`),
    })
}
// 字面段越多越优先：/vms/create-options 先于 /vms/:id
patterns.sort((a, b) => a.params - b.params)

function lookup(method, path) {
  const hit = exact.get(`${method} ${path}`)
  if (hit) return hit
  for (const item of patterns) if (item.route.method === method && item.re.test(path)) return item.route
  return null
}

const exactPaths = new Set(ROUTES.map((route) => route.path))

/** 路径是否以任一方法登记（方法不对时由处理器按原样返回 405） */
export function pathRegistered(path) {
  const p = String(path || '')
  return exactPaths.has(p) || patterns.some((item) => item.re.test(p))
}

/** 按方法与路径查表；HEAD 回落到 GET。没有登记时返回 null。 */
export function matchRoute(method, path) {
  const m = String(method || 'GET').toUpperCase()
  const p = String(path || '')
  return lookup(m, p) || (m === 'HEAD' ? lookup('GET', p) : null)
}

export function routeTableStrict(env = process.env) {
  return env.KIN_ROUTE_TABLE_STRICT === '1'
}

const warned = new Map()
const WARN_INTERVAL_MS = 10 * 60_000

/**
 * 未登记路由的处理：严格模式返回 true（调用方按原有格式回 404）；否则按“方法 + 路径”每 10 分钟告警一次并放行。
 * 路径已登记、只是方法不在表里时放行，由处理器按原样返回 405 或 404。
 */
export function routeTableGuard(method, path, { env = process.env, log = console, now = Date.now } = {}) {
  if (matchRoute(method, path) || pathRegistered(path)) return false
  if (routeTableStrict(env)) return true
  const key = `${String(method || 'GET').toUpperCase()} ${path}`
  const at = now()
  if (warned.size > 1000) warned.clear()
  if (at - (warned.get(key) || 0) >= WARN_INTERVAL_MS) {
    warned.set(key, at)
    log.warn?.(`route table: ${key} is not registered in src/lib/admin/route-table.mjs`)
  }
  return false
}
