export function translate(locale: Locale, text: string): string {
  if (locale === 'zh_CN') return text
  return (
    messages[text]?.[locale === 'en_US' ? 0 : locale === 'zh_TW' ? 1 : 2] ??
    text
  )
}
export function normalizeLocale(value: string | null): Locale {
  return LOCALES.some((l) => l.id === value) ? (value as Locale) : 'zh_CN'
}
